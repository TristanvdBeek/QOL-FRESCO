import sys
import os
import re
import shutil
# requires package installment
import numpy as np


def ExampleUse():
    print("This is script written to automate the process of fetching pdb files from foldx "
          "after having run pyFRESCO (by kt-korbeld) or FRESCO (by hjwijma). \nThe program has the same dependencies as pyFRESCO.\n"
          "To run this program use a command like: \n\tpython fetchPDBs.py $SCRATCH/foldx MutationEnergies_BelowCutOff_FoldX.tab MutationEnergies_BelowCutOff_Rosetta.tab"
          "\nor \n\tpython fetchPDBs.py $SCRATCH/foldx MutationEnergies_BelowCutOff_FoldX.tab \n\n"
          "There is no limit to the number of tab files (as generated by FRESCO) that can be inputted. The mutations are read and duplicates between tab files "
          "are removed. \nThe program will dump all the renamed pdb files into the directory where the program was executed (your current directory as shown by the command \"pwd\")")


def ReadTabFile(tabfile: str) -> np.array:
    '''
    From pyFRESCO by kt-korbeld
    reads specified .tab file (str),
    removes blank first line and 'END' on last line,
    and returns all data in file as a numpy array
    '''
    with open(tabfile) as tab:
        # skip first line to get all data
        TabContents = tab.read().splitlines()
        # check if it starts with empty line and ends with END
    if 'END' in TabContents:
        del(TabContents[TabContents.index('END'):])
    # split entries to nested list, then turn into 2d array
    contents_lst = [re.split('\\s+', res.strip()) for res in TabContents]
    nr_of_columns = len(contents_lst[1])
    if len(contents_lst[0]) != nr_of_columns:
            del(contents_lst[0])
    for i, line in enumerate(contents_lst):
        if len(line) != nr_of_columns:
            del(contents_lst[i:])
            break
    return np.array(contents_lst)


def write_combined_tab(contents_lst: list):
    NAME_OUTPUT_TAB = "combined_mutations.tab"
    np.savetxt(NAME_OUTPUT_TAB, contents_lst, fmt = " %s", header = "Combined mutations")


def combine_mutations(paths_mutation_tabs: list) -> np.array:
    complete_mutation_lst = []
    total_mutations_with_duplicates = 0
    for tab_path in paths_mutation_tabs:
        small_mutation_array = ReadTabFile(tab_path).T[0]
        total_mutations_with_duplicates += len(small_mutation_array)
        for mutation in small_mutation_array:
            if mutation not in complete_mutation_lst:
                complete_mutation_lst.append(mutation)
    print(f"A total of {len(complete_mutation_lst)} mutations were combined from {total_mutations_with_duplicates} mutations. "
          f"{total_mutations_with_duplicates - len(complete_mutation_lst)} duplicates were found.")
    return np.array(complete_mutation_lst)



def CheckError(conditional, errormessage):
    '''
    From pyFRESCO by kt-korbeld
    Takes in conditional statement (Bool) and error message (str).
    Prints error message and quits if conditional is True
    '''
    # print message and end script if condition is met
    if conditional:
        print(f"\n-------- ERROR --------\n{errormessage}")
        sys.exit()


def main():
    ExampleUse()
    # Check if enough arguments are given
    if len(sys.argv) < 3:
        print(f"\n-------- ERROR --------\nToo few arguments were given. At least 2 arguments were expected but {len(sys.argv)-1} were given")
        sys.exit()

    CheckError(os.path.isdir(sys.argv[1]) == False, f"{sys.argv[1]} does not lead to a directory")
    for path in sys.argv[2:]:
        CheckError(os.path.isfile(path) == False, f"{path} does not lead to a file")

    path_foldx_directory: str = sys.argv[1]
    path_tab_files: list = sys.argv[2:]
    mutation_selection: np.array = combine_mutations(path_tab_files)

    if len(path_tab_files) > 1:
        write_combined_tab(mutation_selection)

    start_files_current_dir: int = len(os.listdir("./"))
    
    subdirectories: list = [dr for dr in os.listdir(path_foldx_directory) if dr[:12] == "Subdirectory"]
    #Go over every subdirectory in the foldx directory and read the mutations in the List_Mutations_readable.txt file
    for subdirectory in subdirectories:
        path_subdirectory = os.path.join(path_foldx_directory, subdirectory)
        path_list_mutations = os.path.join(path_subdirectory, "List_Mutations_readable.txt")
        mutations = ReadTabFile(path_list_mutations)
        #Iterate over all mutations in the List_Mutations_readable.txt file
        for mutation_lst in mutations:
            mutation_str = "".join(mutation_lst[1:4])
            #If the mutation if not found in the cutoff list, then skip to the next mutation
            if mutation_str not in mutation_selection:
                continue
            #Make the ending of the .pdb file containing the mutations. Find that pdb file
            pdb_name_end = f"_{mutation_lst[0]}_0.pdb"
            match_name = ''.join([f for f in os.listdir(path_subdirectory) if f[-len(pdb_name_end):] == pdb_name_end and f[0:2] != "WT"])
            #Extract the input name of the .pdb before foldx from the .pdb name
            path_output_pdb = os.path.join("./", f"{match_name[:-len(pdb_name_end)]}_{mutation_str}.pdb")
            #Copy the .pdb to the current directory and rename the file to <name pdb pre-foldx>_<mutation string>.pdb
            shutil.copyfile(os.path.join(path_subdirectory,match_name), path_output_pdb)

    end_files_current_dir: int = len(os.listdir("./"))
    print(f"{end_files_current_dir - start_files_current_dir} "
          f"pdb files were extracted from FoldX.")

    if end_files_current_dir - start_files_current_dir != len(mutation_selection):
        print(f"{len(mutation_selection) - end_files_current_dir + start_files_current_dir} "
              f"mutations were thus not moved to the directory or were already present")

if __name__ == "__main__":
    main()